#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum Extra {
    Phpmyadmin,
    Composer,
    /// Catches the mail PHP sends and shows it in a web inbox.
    Mailpit,
}

impl Extra {
    pub const ALL: [Extra; 3] = [Extra::Phpmyadmin, Extra::Composer, Extra::Mailpit];

    pub fn as_str(self) -> &'static str {
        match self {
            Extra::Phpmyadmin => "phpmyadmin",
            Extra::Composer => "composer",
            Extra::Mailpit => "mailpit",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            Extra::Phpmyadmin => "phpMyAdmin",
            Extra::Composer => "Composer",
            Extra::Mailpit => "Mailpit",
        }
    }
}

pub fn dir(paths: &AppPaths, extra: Extra) -> PathBuf {
    paths.root().join("tools").join(extra.as_str())
}

/// Main file of an installed tool; its presence means the tool is installed.
pub fn file(paths: &AppPaths, extra: Extra) -> PathBuf {
    match extra {
        Extra::Phpmyadmin => dir(paths, extra).join("index.php"),
        Extra::Composer => dir(paths, extra).join("composer.phar"),
        Extra::Mailpit => dir(paths, extra).join(exe("mailpit")),
    }
}

pub async fn install(paths: &AppPaths, extra: &ExtraFile) -> Result<()> {
    let Some(kind) = extra.archive else {
        return installer::fetch_file(&extra.url, &extra.sha256, &file(paths, extra.name)).await;
    };
    let downloads = paths.downloads();
    let archive = downloads.join(format!("{}-{}.archive", extra.name.as_str(), extra.version));
    let result = async {
        installer::fetch_file(&extra.url, &extra.sha256, &archive).await?;
        let (archive, dest) = (archive.clone(), dir(paths, extra.name));
        tokio::task::spawn_blocking(move || installer::extract_into(kind, &archive, &dest))
            .await
            .expect("the extraction task must not panic")
    }
    .await;
    let _ = fs::remove_file(&archive);
    result
}

pub fn uninstall(paths: &AppPaths, extra: Extra) -> Result<()> {
    let dir = dir(paths, extra);
    if dir.exists() {
        fs::remove_dir_all(&dir).at(&dir)?;
    }
    Ok(())
}

/// phpMyAdmin settings: logs straight in as root, which has no password and only listens on 127.0.0.1.
const PHPMYADMIN_CONFIG: &str = r#"<?php
// Generated by Open AMPP: rewritten every time Apache starts.
$cfg['blowfish_secret'] = '{{secret}}';

$i = 1;
$cfg['Servers'][$i]['auth_type'] = 'config';
$cfg['Servers'][$i]['host'] = '127.0.0.1';
$cfg['Servers'][$i]['port'] = '{{port}}';
$cfg['Servers'][$i]['user'] = 'root';
$cfg['Servers'][$i]['password'] = '';
$cfg['Servers'][$i]['AllowNoPassword'] = true;

$cfg['TempDir'] = '{{temp_dir}}';
$cfg['VersionCheck'] = false;
$cfg['SendErrorReports'] = 'never';
"#;

/// If phpMyAdmin is installed, writes its config and returns the Apache block that serves it at `/phpmyadmin`.
pub fn phpmyadmin_apache_conf(paths: &AppPaths, mariadb_port: u16) -> Result<String> {
    if !file(paths, Extra::Phpmyadmin).exists() {
        return Ok(String::new());
    }
    let dir = dir(paths, Extra::Phpmyadmin);
    let temp_dir = dir.join("tmp");
    fs::create_dir_all(&temp_dir).at(&temp_dir)?;
    let config = dir.join("config.inc.php");
    let vars = [
        ("secret", blowfish_secret(paths)),
        ("port", mariadb_port.to_string()),
        ("temp_dir", slash(&temp_dir)),
    ];
    let vars: Vec<(&str, &str)> = vars.iter().map(|(k, v)| (*k, v.as_str())).collect();
    fs::write(&config, config::render(PHPMYADMIN_CONFIG, &vars)).at(&config)?;
    let dir = slash(&dir);
    Ok(format!(
        "Alias /phpmyadmin \"{dir}\"\n<Directory \"{dir}\">\n    DirectoryIndex index.php\n    Require all granted\n</Directory>\n"
    ))
}

/// 32-character secret phpMyAdmin requires; derived from the install path so it stays stable.
fn blowfish_secret(paths: &AppPaths) -> String {
    let digest = Sha256::digest(format!("open-ampp:{}", paths.root().display()));
    hex::encode(digest)[..32].to_string()
}

pub fn shims_dir(paths: &AppPaths) -> PathBuf {
    paths.root().join("shims")
}

/// Terminal command bound to an active tool (`php` → the active PHP with its php.ini).
#[derive(Debug, Clone)]
pub struct Command {
    pub name: &'static str,
    pub program: PathBuf,
    pub args: Vec<String>,
}

/// Commands available for what is installed and active. `cli` is the `ampp` executable, if known.
pub fn commands(paths: &AppPaths, state: &State, cli: Option<&Path>) -> Result<Vec<Command>> {
    let mut cmds = Vec::new();
    let mut add = |name, program: PathBuf, args: Vec<String>| cmds.push(Command { name, program, args });
    let active = |tool| state.active.get(&tool).and_then(|id| install::locate(paths, tool, id).ok());

    if let Some(php) = active(Tool::Php)
        && let Some(cli) = php.php_cli()
    {
        let ini = config::write_php(paths, &php, state)?.ini;
        let base = vec!["-c".to_string(), path_str(&ini)];
        add("php", cli.clone(), base.clone());
        let composer = file(paths, Extra::Composer);
        if composer.exists() {
            add("composer", cli, [base, vec![path_str(&composer)]].concat());
        }
    }
    if let Some(db) = active(Tool::Mariadb) {
        // Passwordless root over loopback: verifying the certificate is pointless (and warns on every use).
        let port = state.ports.mariadb.to_string();
        let conn = ["--protocol=tcp", "-h", "127.0.0.1", "-P", &port, "-u", "root", "--skip-ssl-verify-server-cert"]
            .map(String::from)
            .to_vec();
        if let Some(client) = db.mariadb_client() {
            add("mariadb", client.clone(), conn.clone());
            add("mysql", client, conn.clone());
        }
        let dump = db.root.join("bin").join(exe("mariadb-dump"));
        if dump.exists() {
            add("mariadb-dump", dump.clone(), conn.clone());
            add("mysqldump", dump, conn);
        }
    }
    if let Some(cli) = cli {
        add("ampp", cli.to_path_buf(), Vec::new());
    }
    Ok(cmds)
}

/// Regenerates the `shims/` folder. Returns the command names.
pub fn write_shims(paths: &AppPaths, state: &State, cli: Option<&Path>) -> Result<Vec<String>> {
    let cmds = commands(paths, state, cli)?;
    let dir = shims_dir(paths);
    if dir.exists() {
        fs::remove_dir_all(&dir).at(&dir)?;
    }
    fs::create_dir_all(&dir).at(&dir)?;
    for cmd in &cmds {
        write_shim(&dir, cmd.name, &cmd.program, &cmd.args)?;
    }
    Ok(cmds.into_iter().map(|c| c.name.to_string()).collect())
}

fn path_str(path: &Path) -> String {
    path.to_string_lossy().into_owned()
}

fn write_shim(dir: &Path, name: &str, program: &Path, args: &[String]) -> Result<()> {
    let quoted: Vec<String> = std::iter::once(path_str(program)).chain(args.iter().cloned()).map(|a| format!("\"{a}\"")).collect();
    if cfg!(windows) {
        let path = dir.join(format!("{name}.cmd"));
        fs::write(&path, format!("@echo off\r\nrem Generado por Open AMPP.\r\n{} %*\r\n", quoted.join(" "))).at(&path)
    } else {
        let path = dir.join(name);
        fs::write(&path, format!("#!/bin/sh\n# Generado por Open AMPP.\nexec {} \"$@\"\n", quoted.join(" "))).at(&path)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            fs::set_permissions(&path, fs::Permissions::from_mode(0o755)).at(&path)?;
        }
        Ok(())
    }
}

const PATH_MARKER: &str = "# >>> Open AMPP >>>";

/// Shell startup files where the shims folder is added to the PATH.
/// The first one is created if missing; the others are only touched if they exist.
#[cfg(unix)]
fn shell_rc_files() -> Vec<PathBuf> {
    let Some(home) = directories::BaseDirs::new().map(|d| d.home_dir().to_path_buf()) else {
        return Vec::new();
    };
    let names: &[&str] =
        if cfg!(target_os = "macos") { &[".zshrc", ".bash_profile"] } else { &[".bashrc", ".zshrc"] };
    names
        .iter()
        .enumerate()
        .map(|(i, n)| (i, home.join(n)))
        .filter(|(i, p)| *i == 0 || p.exists())
        .map(|(_, p)| p)
        .collect()
}

/// `true` if the shims folder is already set up on the user's PATH.
pub fn shims_on_path(paths: &AppPaths) -> bool {
    #[cfg(unix)]
    {
        let _ = paths;
        shell_rc_files().iter().any(|f| fs::read_to_string(f).is_ok_and(|s| s.contains(PATH_MARKER)))
    }
    #[cfg(windows)]
    {
        windows_user_path().is_some_and(|p| p.split(';').any(|d| Path::new(d) == shims_dir(paths)))
    }
}

/// Adds the shims folder to the user's PATH (shell files on Unix, the user variable on Windows).
/// Idempotent. Returns where it was applied.
pub fn add_shims_to_path(paths: &AppPaths) -> Result<Vec<String>> {
    let dir = shims_dir(paths);
    #[cfg(unix)]
    {
        let block = format!("\n{PATH_MARKER}\nexport PATH=\"{}:$PATH\"\n# <<< Open AMPP <<<\n", dir.display());
        let mut touched = Vec::new();
        for rc in shell_rc_files() {
            let current = fs::read_to_string(&rc).unwrap_or_default();
            if !current.contains(PATH_MARKER) {
                fs::write(&rc, current + &block).at(&rc)?;
            }
            touched.push(rc.display().to_string());
        }
        Ok(touched)
    }
    #[cfg(windows)]
    {
        let dir = dir.display().to_string().replace('\'', "''");
        let script = format!(
            "$p=[Environment]::GetEnvironmentVariable('Path','User'); \
             if (-not (($p -split ';') -contains '{dir}')) {{ \
             [Environment]::SetEnvironmentVariable('Path', ('{dir};' + $p).TrimEnd(';'), 'User') }}"
        );
        let status = powershell(&script).status().at("powershell")?;
        if !status.success() {
            return Err(crate::Error::InvalidSetting(tr!("no se pudo modificar el PATH del usuario", "could not update the user PATH")));
        }
        Ok(vec![tr!("PATH del usuario", "user PATH")])
    }
}

#[cfg(windows)]
fn powershell(script: &str) -> std::process::Command {
    use std::os::windows::process::CommandExt;
    let mut cmd = std::process::Command::new("powershell");
    cmd.args(["-NoProfile", "-NonInteractive", "-Command", script]).creation_flags(0x0800_0000);
    cmd
}

#[cfg(windows)]
fn windows_user_path() -> Option<String> {
    let out = powershell("[Environment]::GetEnvironmentVariable('Path','User')").output().ok()?;
    Some(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uninstall_removes_the_tool_folder() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = AppPaths::new(tmp.path());
        uninstall(&paths, Extra::Composer).unwrap();
        fs::create_dir_all(dir(&paths, Extra::Composer)).unwrap();
        fs::write(file(&paths, Extra::Composer), "").unwrap();
        uninstall(&paths, Extra::Composer).unwrap();
        assert!(!dir(&paths, Extra::Composer).exists());
        assert_eq!(Extra::ALL.map(Extra::label), ["phpMyAdmin", "Composer", "Mailpit"]);
    }

    #[test]
    fn shims_point_to_active_php_and_composer() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = AppPaths::new(tmp.path());
        let php_root = paths.bin(Tool::Php, "8.4.1");
        fs::create_dir_all(&php_root).unwrap();
        fs::write(php_root.join(exe("php")), "").unwrap();
        fs::create_dir_all(dir(&paths, Extra::Composer)).unwrap();
        fs::write(file(&paths, Extra::Composer), "").unwrap();
        let mut state = State::default();
        state.mark_installed(Tool::Php, "8.4.1");

        let names = write_shims(&paths, &state, None).unwrap();
        assert_eq!(names, ["php", "composer"]);
        let shim = if cfg!(windows) { "composer.cmd" } else { "composer" };
        let text = fs::read_to_string(shims_dir(&paths).join(shim)).unwrap();
        assert!(text.contains("composer.phar"));
        assert!(text.contains("php.ini"), "must use the Open AMPP php.ini: {text}");
    }

    #[test]
    fn phpmyadmin_conf_only_when_installed() {
        let tmp = tempfile::tempdir().unwrap();
        let paths = AppPaths::new(tmp.path());
        assert_eq!(phpmyadmin_apache_conf(&paths, 3306).unwrap(), "");

        fs::create_dir_all(dir(&paths, Extra::Phpmyadmin)).unwrap();
        fs::write(file(&paths, Extra::Phpmyadmin), "").unwrap();
        let conf = phpmyadmin_apache_conf(&paths, 3307).unwrap();
        assert!(conf.contains("Alias /phpmyadmin"));
        let config = fs::read_to_string(dir(&paths, Extra::Phpmyadmin).join("config.inc.php")).unwrap();
        assert!(config.contains("['port'] = '3307'"));
        let secret = config.split("blowfish_secret'] = '").nth(1).unwrap().split('\'').next().unwrap();
        assert_eq!(secret.len(), 32, "phpMyAdmin requires a 32-byte secret");
    }
}
